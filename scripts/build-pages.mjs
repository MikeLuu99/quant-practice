// Builds a static Pages bundle for one mode: a copy of the Astro dist plus a
// generated advanced-mode `_worker.js` that proxies /api/* (and /healthz) to
// the full-stack API Worker, serving everything else from static assets.
// Usage: node scripts/build-pages.mjs staging|production
import { cp, mkdir, rm, writeFile } from 'node:fs/promises';

const mode = process.argv[2] === 'production' ? 'production' : 'staging';
const origin = (process.env.QUANT_API_ORIGIN || process.env.QUANT_BASE_URL || '').replace(/\/+$/, '');
if (!/^https:\/\/[a-z0-9.-]+$/.test(origin)) {
  throw Error('Set QUANT_API_ORIGIN to the API Worker URL, e.g. https://quant-practice-staging.<subdomain>.workers.dev');
}

const dist = new URL('../frontend/dist/', import.meta.url);
const out = new URL(`../.cloudflare/pages/${mode}/`, import.meta.url);
await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
await cp(dist, out, { recursive: true });

const worker = `// Generated by scripts/build-pages.mjs (${mode}). Do not edit.
const API_ORIGIN = ${JSON.stringify(origin)};
const PROXIED = (path) => path.startsWith('/api/') || path === '/healthz';

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    if (!PROXIED(url.pathname)) return env.ASSETS.fetch(request);
    const upstream = await fetch(new Request(API_ORIGIN + url.pathname + url.search, request));
    const headers = new Headers(upstream.headers);
    headers.set('Cache-Control', 'no-store');
    return new Response(upstream.body, { status: upstream.status, headers });
  },
};
`;
await writeFile(new URL('_worker.js', out), worker);
console.log(`Pages bundle (${mode}): ${out.pathname} -> API ${origin}`);
